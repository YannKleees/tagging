# Spellings in common use that Wikidata has no label for.
EXTRA = {"Ernzen": ["Iernz"]}

RAW = Path(__file__).with_name("raw")


def fetch(sparql):
    data = urllib.parse.urlencode({"query": sparql}).encode()
    req = urllib.request.Request(ENDPOINT, data, {"Accept": "text/csv", "User-Agent": "tagging-gazetteer/0.1"})
    # The public endpoint times out intermittently on the subclass query.
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=180) as r:
                return r.read().decode("utf-8")
        except urllib.error.HTTPError as e:
            if e.code < 500 or attempt == 3:
                raise
            time.sleep(10 * (attempt + 1))


def clean(x):
    x = re.sub(r"\s*\(.*\)$", "", x).strip()
    x = re.sub(r",\s*Luxembourg$", "", x)
    return x if x and not re.search(r"\d", x) else ""


if "--offline" not in sys.argv:
    RAW.mkdir(exist_ok=True)
    for name, q in QUERIES.items():
        (RAW / name).write_text(fetch(q), encoding="utf-8", newline="")

# Everyday words from Wikipedia text catch what the hand-kept list misses: `Soup`, `Pull`, `Gëlt`.
COMMON = Path(__file__).parents[2] / "tagging" / "common_words.txt"
common = {w.lstrip("~") for w in COMMON.read_text(encoding="utf-8").splitlines() if not w.startswith("#")}


def ambiguous(x):
    return x in AMBIGUOUS or x.lower() in common


rows = [r for name in QUERIES for r in csv.DictReader(io.StringIO((RAW / name).read_text(encoding="utf-8")))]
places = {}
for r in rows:
    if r["type"] not in KEEP:
        continue
    names = places.setdefault(r["item"], [])
    for k in ("lb", "fr", "de", "en"):
        x = clean(r[k])
        if x and x not in names and x not in DROP:
            names.append(x)
            names += [y for y in EXTRA.get(x, []) if y not in names]

lines = set()
for v in places.values():
    plain = [x for x in v if not ambiguous(x)]
    lines |= {"~" + x for x in v if ambiguous(x)}
    if plain:
        lines.add("|".join(plain))
lines = sorted(lines, key=lambda x: x.lstrip("~").casefold())
header = [
    "# Luxembourg communes and localities (Luxembourgish|French|German|English labels).",
    "# Generated by build_places.py from Wikidata (CC0); raw query results are in raw/.",
    "# '~' marks names that are also common words; they are matched with a lower score.",
]
out = Path(__file__).with_name("lu_places.txt")
out.write_text("\n".join(header + lines) + "\n", encoding="utf-8", newline="\n")
print(len(lines), "places written to", out)
