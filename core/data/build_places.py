ENDPOINT = "https://query.wikidata.org/sparql"
LABELS = """
OPTIONAL{?item rdfs:label ?lb FILTER(lang(?lb)="lb")}
OPTIONAL{?item rdfs:label ?fr FILTER(lang(?fr)="fr")}
OPTIONAL{?item rdfs:label ?de FILTER(lang(?de)="de")}
OPTIONAL{?item rdfs:label ?en FILTER(lang(?en)="en")}
"""
QUERIES = {
    "communes.csv": f"""SELECT ?item ?lb ?fr ?de ?en ?type WHERE {{
?item wdt:P31 wd:Q2919801. FILTER NOT EXISTS {{?item wdt:P576 ?end}}
BIND("commune" AS ?type) {LABELS} }}""",
    "settlements.csv": f"""SELECT ?item ?lb ?fr ?de ?en ?type WHERE {{
?item wdt:P17 wd:Q32; wdt:P31 ?t. ?t wdt:P279* wd:Q486972.
?t rdfs:label ?type FILTER(lang(?type)="en") {LABELS} }}""",
}

