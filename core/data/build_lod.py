"""Builds raw/lod_words.txt: every word form of the Lëtzebuerger Online Dictionnaire (LOD) that is
not a proper noun. build_common_words.py adds them to the everyday words, which the Luxembourgish
Wikipedia alone covers poorly (`Hiewan`, `Coiffer`, `Kaffi`).

The LOD is published by the Zenter fir d'Lëtzebuerger Sprooch on data.public.lu under CC0.
"""

import io
import json
import re
import urllib.request
import zipfile
from pathlib import Path

API = "https://data.public.lu/api/1/datasets/{}/"
ENTRIES = "letzebuerger-online-dictionnaire-lod-linguistesch-daten"
TABLES = "letzebuerger-online-dictionnaire-lod-flexiounstabellen"
OUT = Path(__file__).parent / "raw" / "lod_words.txt"
PROPER_NOUN = "NP"
WORD = re.compile(r"[^\W\d_]+(?:-[^\W\d_]+)*")


# The newest file of a dataset, unpacked.
def latest(dataset):
    with urllib.request.urlopen(API.format(dataset), timeout=60) as r:
        resources = json.load(r)["resources"]
    newest = max(resources, key=lambda x: x["created_at"])
    with urllib.request.urlopen(newest["url"], timeout=300) as r:
        archive = zipfile.ZipFile(io.BytesIO(r.read()))
    return newest["title"], archive.read(archive.namelist()[0]).decode("utf-8")


def main():
    title, xml = latest(ENTRIES)
    words, names = set(), set()
    for entry in xml.split("<entry id=")[1:]:
        lemma = re.search(r"<lemma>([^<]+)</lemma>", entry)
        if not lemma:
            continue
        forms = [lemma.group(1), *re.findall(r"<form[^>]*>([^<]+)</form>", entry)]
        proper = PROPER_NOUN in re.findall(r"<partOfSpeech[^>]*>([^<]+)</partOfSpeech>", entry)
        (names if proper else words).update(w for form in forms for w in WORD.findall(form))
    # Declined adjectives, conjugated verbs and plurals; the leaves of the table file are word forms.
    table_title, tables = latest(TABLES)
    words.update(w for leaf in re.findall(r">([^<>\n]+)</", tables) for w in WORD.findall(leaf))
    lowered = {w.lower() for w in words if len(w) >= 2} - {n.lower() for n in names}
    header = [
        "# Word forms of the Lëtzebuerger Online Dictionnaire (lod.lu, CC0) without its proper nouns.",
        f"# Generated by build_lod.py from {title} and {table_title}.",
    ]
    OUT.write_text("\n".join(header + sorted(lowered)) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(lowered)} words to {OUT.name}")


if __name__ == "__main__":
    main()
