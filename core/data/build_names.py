import csv
import io
import re
import sys
import time
import unicodedata
import urllib.error
import urllib.parse
import urllib.request
from collections import Counter
from pathlib import Path

ENDPOINT = "https://query.wikidata.org/sparql"
# Citizenship of Luxembourg, its neighbours and the largest foreign communities living there.
COUNTRIES = {
    "LU": "Q32", "BE": "Q31", "FR": "Q142", "DE": "Q183", "PT": "Q45",
    "IT": "Q38", "GB": "Q145", "NL": "Q55", "ES": "Q29",
}  # fmt: skip
# P735 is the given name, P734 the family name, P1705 the name in its own spelling.
PROPS = {"given": "P735", "family": "P734"}
QUERY = (
    "SELECT ?l (COUNT(?h) AS ?n) WHERE {{ ?h wdt:P27 wd:{country}; wdt:{prop} ?name. ?name wdt:P1705 ?l }} GROUP BY ?l"
)

HERE = Path(__file__).parent
RAW = HERE / "raw"
COMMON = HERE.parents[1] / "tagging" / "common_words.txt"
LATIN = re.compile(r"^[A-Za-zÀ-ÖØ-öø-ÿĀ-ſ'’-]+$")
# Rows kept in raw/: people counted across all countries, or at least one in Luxembourg.
RAW_MIN = {"given": 5, "family": 4}
# Names written to the lists.
GIVEN_MIN, GIVEN_MIN_LU = 15, 2
FAMILY_MIN, FAMILY_MIN_LU = 8, 1
# A family name that is an everyday word needs this many bearers to stay.
FAMILY_MIN_COMMON = 40


def fetch(sparql):
    data = urllib.parse.urlencode({"query": sparql}).encode()
    req = urllib.request.Request(ENDPOINT, data, {"Accept": "text/csv", "User-Agent": "tagging-gazetteer/0.1"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=180) as r:
                return r.read().decode("utf-8")
        except (urllib.error.HTTPError, TimeoutError) as e:
            if getattr(e, "code", 500) < 500 or attempt == 3:
                raise
            time.sleep(10 * (attempt + 1))


def download(kind):
    total, lu = Counter(), Counter()
    for code, country in COUNTRIES.items():
        # A name item often carries one spelling under several language tags, and the query returns
        # a row for each. Keeping the highest count per spelling removes those repeats.
        people = Counter()
        for r in csv.DictReader(io.StringIO(fetch(QUERY.format(country=country, prop=PROPS[kind])))):
            name = unicodedata.normalize("NFC", r["l"].strip())
            if LATIN.match(name) and len(name) >= 2 and name[0].isupper():
                people[name] = max(people[name], int(r["n"]))
        total.update(people)
        if code == "LU":
            lu.update(people)
    keep = sorted(n for n in total if total[n] >= RAW_MIN[kind] or lu[n])
    with open(RAW / f"{kind}_names.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["name", "people", "people_lu"])
        w.writerows([n, total[n], lu[n]] for n in keep)


def counts(kind):
    with open(RAW / f"{kind}_names.csv", encoding="utf-8") as f:
        return {r["name"]: (int(r["people"]), int(r["people_lu"])) for r in csv.DictReader(f)}


# `common_words.txt` marks words that are both everyday words and names with `~`.
def common_words():
    plain, marked = set(), set()
    for line in COMMON.read_text(encoding="utf-8").splitlines():
        (marked if line.startswith("~") else plain).add(line.lstrip("~"))
    return plain, marked


# Single-word names in the place and organization lists: `Paris`, `Florence`, `Mercedes`.
def listed_elsewhere():
    names = set()
    for path in [*HERE.glob("lu_places.txt"), *HERE.glob("lu_organizations.txt"), *HERE.glob("world_*.txt")]:
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.startswith("#"):
                names |= {n.strip() for n in line.lstrip("~?").split("|")}
    return names


def write(path, header, lines):
    path.write_text("\n".join(header + lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(lines)} names to {path.name}")


def main():
    if "--offline" not in sys.argv:
        RAW.mkdir(exist_ok=True)
        for kind in PROPS:
            download(kind)
    plain, marked = common_words()
    common = plain | marked

    # Hyphenated first names (`Jean-Claude`) are matched part by part, so only the parts are listed.
    given = sorted(
        n for n, (people, lu) in counts("given").items() if (people >= GIVEN_MIN or lu >= GIVEN_MIN_LU) and "-" not in n
    )
    elsewhere = listed_elsewhere()
    weak = {n for n in given if len(n) < 3 or n.lower() in common or n in elsewhere}
    write(
        HERE / "given_names.txt",
        [
            "# First names of people with Luxembourgish, Belgian, French, German, Portuguese, Italian, British,",
            "# Dutch or Spanish citizenship. Generated by build_names.py from Wikidata (CC0).",
            "# '?' marks names that are also everyday words, places or organizations (`Rose`, `Paris`);",
            "# they only match next to another name part.",
        ],
        [f"?{n}" if n in weak else n for n in given],
    )

    family = sorted(
        n
        for n, (people, lu) in counts("family").items()
        if (people >= FAMILY_MIN or lu >= FAMILY_MIN_LU) and (n.lower() not in plain or people >= FAMILY_MIN_COMMON)
    )
    write(
        HERE / "family_names.txt",
        [
            "# Family names from the same Wikidata query as given_names.txt. Generated by build_names.py (CC0).",
            "# A family name never matches on its own, only after a first name or a title.",
            "# '?' marks names that are also everyday words; they do not name a business (`Hotel Zimmer`).",
        ],
        [f"?{n}" if n.lower() in common else n for n in family],
    )


if __name__ == "__main__":
    main()
